import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import test from 'node:test';
import assert from 'node:assert/strict';

const path=new URL('./cinematic-benchmark.jsx',import.meta.url);

test('cinematic benchmark exists and rejects the old doodle/SVG visual grammar',()=>{
  assert.equal(fs.existsSync(path),true,'cinematic-benchmark.jsx must exist');
  const src=fs.readFileSync(path,'utf8');
  assert.match(src,/WhatIfCinematicBenchmark/);
  assert.match(src,/APPROVED_BENCHMARK_VOICE\s*=\s*['"]af_heart['"]/);
  assert.match(src,/imageAssetsForScene/);
  assert.match(src,/staticFile\(shot\.source\)/);
  assert.doesNotMatch(src,/photoshop-api|am_michael|Brian/i);
  assert.doesNotMatch(src,/SleepAssetScene|sleep-scenes|\.svg|doodle|stick figure/i);
});

test('human shot transitions use motivated cuts instead of ghosted double-exposure crossfades',()=>{
  const src=fs.readFileSync(path,'utf8');
  assert.doesNotMatch(src,/fadeIn|fadeOut|Math\.min\(fadeIn,fadeOut\)/);
});

test('benchmark consumes the exact locked editorial narration generated by its workflow',()=>{
  const src=fs.readFileSync(path,'utf8');
  assert.match(src,/staticFile\(['"]editorial-narration\.mp3['"]\)/);
  assert.doesNotMatch(src,/benchmark-narration\.mp3/);
});

test('doodle renderer proof covers and actually renders all representative scene classes',()=>{
  const proofPath=new URL('./doodle-renderer-proof.jsx',import.meta.url);
  const plusPath=new URL('./doodle-explainer-plus.jsx',import.meta.url);
  assert.equal(fs.existsSync(proofPath),true);
  assert.equal(fs.existsSync(plusPath),true);
  const proof=fs.readFileSync(proofPath,'utf8');
  for(const token of ['single-character','two-character','character-prop','environment','diagram','comparison','timeline','map','stat','transformation']) assert.match(proof,new RegExp(token));
  const plus=fs.readFileSync(plusPath,'utf8');
  assert.match(plus,/kind==='timeline'/);
  assert.match(plus,/kind==='map'/);
  const frames=[45,135,225,315,405,495,585,675,765,855];
  for(const [index,frame] of frames.entries()){
    const output=`/tmp/doodle-proof-${String(index+1).padStart(2,'0')}.png`;
    execFileSync('npx',['remotion','still','video/src/index.jsx','WhatIfDoodleRendererProof',output,`--frame=${frame}`],{stdio:'inherit'});
    assert.equal(fs.existsSync(output),true,`proof frame ${index+1} must exist`);
    assert.ok(fs.statSync(output).size>1000,`proof frame ${index+1} must not be empty`);
  }
});
